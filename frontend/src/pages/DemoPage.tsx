import { useEffect, useState } from 'react';
import { FlaskConical, RefreshCw, AlertTriangle } from 'lucide-react';
import { useDemoRisk } from '../hooks/useDemoRisk';
import { DemoBanner } from '../components/ui/DemoBanner';
import { RiskTable } from '../components/ui/RiskTable';
import { RiskBarChart } from '../components/charts/RiskBarChart';
import type { SiteRankOutput } from '../types/api';
import { riskColor, riskBadgeClass, scorePercent } from '../utils/risk';
import { ScoreGauge } from '../components/ui/ScoreGauge';

export function DemoPage() {
  const { data, loading, error, load } = useDemoRisk();
  const [selected, setSelected] = useState<SiteRankOutput | null>(null);

  useEffect(() => { load(); }, [load]);
  useEffect(() => {
    if (data?.ranked_sites.length) setSelected(data.ranked_sites[0]);
  }, [data]);

  return (
    <div className="page-scroll fade-in">
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
        <div className="section-heading">
          <span className="hl" /><FlaskConical size={18} /> Demo Simulation
        </div>
        <button className="btn btn-ghost" onClick={load} disabled={loading}>
          <RefreshCw size={13} />
          Reload Demo
        </button>
      </div>

      <DemoBanner />

      <div style={{ padding: '10px 16px', background: 'rgba(59,130,246,0.08)', borderRadius: 8, border: '1px solid rgba(59,130,246,0.2)', fontSize: 12, color: 'var(--text-secondary)', lineHeight: 1.7 }}>
        <strong style={{ color: 'var(--text-accent)' }}>Data Provenance Notice:</strong>{' '}
        The 10 demo sites (SITE_CATCH_001…010) are synthetic scenarios generated by the
        {' '}<code style={{ fontFamily: 'monospace', color: 'var(--accent-cyan)' }}>/api/demo/risk</code>{' '}
        endpoint. Site IDs, coordinates, sensor readings, and CCTV image references are
        fabricated for demonstration purposes only. No real municipal locations, drainage
        networks, or live sensor telemetry are represented.
      </div>

      {error && (
        <div style={{ fontSize: 13, color: 'var(--risk-critical)', padding: '12px 16px', background: 'rgba(239,68,68,0.08)', borderRadius: 8, border: '1px solid rgba(239,68,68,0.25)', display: 'flex', gap: 8, alignItems: 'center' }}>
          <AlertTriangle size={14} /> {error}
        </div>
      )}

      {loading && !data && <div className="card empty-state"><div className="spinner" /><p>Loading simulation…</p></div>}

      {data && (
        <>
          <div className="grid-2" style={{ alignItems: 'start' }}>
            {/* Site list */}
            <div className="card">
              <div className="card-header">
                <div className="card-title">Simulated Sites</div>
                <span style={{ fontSize: 12, color: 'var(--text-muted)' }}>{data.total_sites} sites</span>
              </div>
              <div style={{ display: 'flex', flexDirection: 'column', gap: 8 }}>
                {data.ranked_sites.map(site => (
                  <button
                    key={site.site_id}
                    onClick={() => setSelected(site)}
                    style={{
                      display: 'flex', alignItems: 'center', gap: 12,
                      padding: '10px 12px', borderRadius: 8, cursor: 'pointer',
                      border: `1px solid ${selected?.site_id === site.site_id ? 'var(--accent-blue)' : 'var(--border-muted)'}`,
                      background: selected?.site_id === site.site_id ? 'rgba(59,130,246,0.1)' : 'var(--bg-surface)',
                      textAlign: 'left', width: '100%', transition: 'all 0.15s',
                    }}
                  >
                    <span style={{ width: 28, height: 28, borderRadius: '50%', display: 'flex', alignItems: 'center', justifyContent: 'center', background: `${riskColor(site.risk_level as any)}22`, color: riskColor(site.risk_level as any), fontSize: 11, fontWeight: 700, flexShrink: 0 }}>
                      {site.rank}
                    </span>
                    <div style={{ flex: 1 }}>
                      <div style={{ fontSize: 12, fontWeight: 600, color: 'var(--text-primary)', fontFamily: 'JetBrains Mono, monospace' }}>{site.site_id}</div>
                      <div style={{ fontSize: 11, color: 'var(--text-muted)', marginTop: 2 }}>{scorePercent(site.composite_risk_score)} risk</div>
                    </div>
                    <span className={`badge ${riskBadgeClass(site.risk_level as any)}`}>{site.risk_level}</span>
                  </button>
                ))}
              </div>
            </div>

            {/* Selected site detail */}
            {selected && (
              <div style={{ display: 'flex', flexDirection: 'column', gap: 16 }}>
                <div className="card fade-in">
                  <div className="card-header">
                    <div>
                      <div className="card-title">Site Detail</div>
                      <div style={{ fontSize: 14, fontWeight: 700, color: 'var(--text-primary)', marginTop: 2, fontFamily: 'JetBrains Mono, monospace' }}>{selected.site_id}</div>
                    </div>
                    <ScoreGauge score={selected.composite_risk_score} level={selected.risk_level as any} size={70} />
                  </div>

                  <div className="grid-2" style={{ gap: 10, marginBottom: 14 }}>
                    <DetailRow label="Rank"       value={`#${selected.rank}`}                   />
                    <DetailRow label="Level"      value={selected.risk_level} color={riskColor(selected.risk_level as any)} />
                    <DetailRow label="Composite"  value={scorePercent(selected.composite_risk_score)} color={riskColor(selected.risk_level as any)} />
                    <DetailRow label="Blockage"   value={scorePercent(selected.blockage_score)} color="var(--accent-blue)" />
                    <DetailRow label="Overflow"   value={scorePercent(selected.overflow_score)} color="var(--accent-cyan)" />
                    <DetailRow label="Rainfall"   value={scorePercent(selected.rainfall_score)} color="var(--accent-teal)" />
                  </div>

                  {selected.metadata && Object.keys(selected.metadata).length > 0 && (
                    <div style={{ borderTop: '1px solid var(--border-muted)', paddingTop: 12, marginTop: 4 }}>
                      <div className="card-title" style={{ marginBottom: 8 }}>Metadata</div>
                      <div style={{ display: 'flex', flexDirection: 'column', gap: 4 }}>
                        {Object.entries(selected.metadata).map(([k, v]) => (
                          <div key={k} style={{ display: 'flex', gap: 8, fontSize: 12 }}>
                            <span style={{ color: 'var(--text-muted)', minWidth: 140 }}>{k}</span>
                            <span style={{ color: 'var(--text-secondary)', fontFamily: 'JetBrains Mono, monospace', fontSize: 11 }}>{String(v)}</span>
                          </div>
                        ))}
                      </div>
                    </div>
                  )}
                </div>
              </div>
            )}
          </div>

          {/* Chart */}
          <div className="card">
            <div className="card-header">
              <div className="card-title">All Sites — Risk Score Comparison</div>
              <span className="chip">Simulation</span>
            </div>
            <RiskBarChart sites={data.ranked_sites} />
          </div>

          {/* Full table */}
          <div className="card">
            <div className="card-header"><div className="card-title">Full Ranked Table</div></div>
            <RiskTable sites={data.ranked_sites} />
          </div>
        </>
      )}
    </div>
  );
}

function DetailRow({ label, value, color }: { label: string; value: string; color?: string }) {
  return (
    <div style={{ background: 'var(--bg-surface)', borderRadius: 6, padding: '8px 12px' }}>
      <div style={{ fontSize: 10, fontWeight: 600, textTransform: 'uppercase' as const, color: 'var(--text-muted)', marginBottom: 2, letterSpacing: '0.06em' }}>{label}</div>
      <div style={{ fontSize: 14, fontWeight: 700, color: color ?? 'var(--text-primary)', fontVariantNumeric: 'tabular-nums' }}>{value}</div>
    </div>
  );
}
